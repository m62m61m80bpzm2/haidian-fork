def run(tag, img, prompt, max_retry=3):
    out = os.path.join(OUTDIR, f"qc_{tag}.json")
    if os.path.exists(out) and os.path.getsize(out) > 10:
        log(f"SKIP {tag}")
        return True
    for attempt in range(1, max_retry + 1):
        cmd = ["z-ai", "vision", "-p", prompt, "-i", os.path.join(BASE, img), "-o", out]
        try:
            r = subprocess.run(cmd, capture_output=True, text=True, timeout=180)
        except subprocess.TimeoutExpired:
            log(f"TIMEOUT {tag} attempt={attempt}")
            time.sleep(30); continue
        if r.returncode == 0 and os.path.exists(out) and os.path.getsize(out) > 10:
            log(f"DONE {tag} attempt={attempt}")
            time.sleep(20)  # 控制请求频率
            return True
        err = (r.stderr or r.stdout or "")[-200:].replace("\n", " ")
        log(f"RETRY {tag} attempt={attempt} err={err}")
        time.sleep(60 if "429" in err else 25)
    log(f"FAILED {tag}")
    return False

if __name__ == "__main__":
    only = set(sys.argv[1:])
    for tag, img, prompt in TASKS:
        if only and tag not in only:
            continue
        run(tag, img, prompt)
    log("ALL FINISHED")
